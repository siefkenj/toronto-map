#!/usr/bin/env python3
"""Generate src/render/fontMetrics.ts from the embedded web fonts.

The renderer has to know how wide a string will be before it draws it, and it
has no DOM to ask. It used to guess with a five-bucket table of average
advances; this measures the real fonts instead, which is what lets the gazetteer
be line-broken and justified without visible error.

Both EB Garamond faces are VARIABLE fonts (wght 400-800 with an HVAR table), so
a glyph's advance depends on the weight it is drawn at. The panel sets entry
names at weight 600, so that instance is measured separately -- reading semibold
text off the regular metrics under-measures every name, which is exactly the bug
that made the gap after an entry's name collapse.

Requires `pip install fonttools brotli`. Output is committed; only re-run when
the fonts change:

    npm run font-metrics
"""
import json
import pathlib
import sys

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

HERE = pathlib.Path(__file__).resolve().parent
FONTS = HERE.parent / "src" / "assets" / "fonts"
OUT = HERE.parent / "src" / "render" / "fontMetrics.ts"

# face key -> (file, weight to measure at)
FACES = {
    "serif": ("ebgaramond-regular.woff2", 400),
    "serifBold": ("ebgaramond-regular.woff2", 600),
    "italic": ("ebgaramond-italic.woff2", 400),
    "display": ("playfair-700.woff2", 700),
}

CHARS = [chr(c) for c in range(32, 127)] + list(
    "£©–—‘’“”…·×àáâäçèéêëíîïñóôöúûüÀÁÂÄÇÈÉÊËÍÎÏÑÓÔÖÚÛÜ"
)


def metrics_for(path: pathlib.Path, weight: int) -> dict:
    font = TTFont(path)
    if "fvar" in font:
        axes = {a.axisTag: a for a in font["fvar"].axes}
        if "wght" in axes:
            a = axes["wght"]
            w = min(max(weight, a.minValue), a.maxValue)
            font = instantiateVariableFont(font, {"wght": w}, updateFontNames=False)
    upm = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    adv = {}
    for ch in CHARS:
        name = cmap.get(ord(ch))
        if name is None or name not in hmtx.metrics:
            continue
        adv[ch] = round(hmtx.metrics[name][0] / upm, 4)
    return {"adv": adv, "fallback": adv.get("n", 0.5)}


faces = {}
for key, (file, weight) in FACES.items():
    faces[key] = metrics_for(FONTS / file, weight)
    print(f"{key:<10} {file:<28} wght {weight:<4} {len(faces[key]['adv'])} glyphs")

lines = [
    "// AUTO-GENERATED by scripts/build_font_metrics.py — do not edit by hand.",
    "//",
    "// Advance widths measured from the embedded fonts, in em units (multiply by",
    "// font-size). Used for line breaking and justification so the widths the layout",
    "// computes match what the renderer will actually draw.",
    "//",
    "// `serifBold` is the same face as `serif` instanced at weight 600 — the variable",
    "// axis makes it measurably wider, and the gazetteer sets entry names at that",
    "// weight. No kern pairs: these faces kern through GPOS class pair-positioning,",
    "// which the renderer applies when it draws; over a ~90-character line that",
    "// shifts the width by well under half a percent, which the word spaces absorb.",
    "",
    "export interface FaceMetrics {",
    "    /** advance width per character, in em */",
    "    adv: Record<string, number>;",
    "    /** advance used for any character not in `adv` */",
    "    fallback: number;",
    "}",
    "",
]
for key, m in faces.items():
    const = "".join("_" + c if c.isupper() else c.upper() for c in key).upper()
    lines.append(f"export const {const}_METRICS: FaceMetrics = {json.dumps(m, ensure_ascii=False)};")
    lines.append("")

lines.append("export const FACE_METRICS: Record<string, FaceMetrics> = {")
for key in faces:
    const = "".join("_" + c if c.isupper() else c.upper() for c in key).upper()
    lines.append(f"    {key}: {const}_METRICS,")
lines.append("};")
lines.append("")

OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {OUT.relative_to(HERE.parent)}")
